from django.db import models
from django.contrib.auth.models import User
import uuid
from django.db.models.signals import post_save
from django.dispatch import receiver


class ServiceToken(models.Model):
    """
    Service tokens for external applications (Reflection, ByteBridge)
    Generated by NeuroController, validated by NeuroController
    """
    token_id = models.UUIDField(default=uuid.uuid4, unique=True, editable=False)
    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name='service_tokens')

    # Token details
    token_hash = models.CharField(max_length=64, unique=True, db_index=True)
    application_name = models.CharField(max_length=100)

    # Target application (reflection, bytebridge)
    target_app = models.CharField(max_length=50, default='reflection')

    # Permissions
    scopes = models.TextField(default='read,visualize')

    # Timestamps
    created_at = models.DateTimeField(auto_now_add=True)
    expires_at = models.DateTimeField()
    last_used = models.DateTimeField(null=True, blank=True)

    # Status
    is_active = models.BooleanField(default=True)
    revoked_at = models.DateTimeField(null=True, blank=True)

    # Client info (for audit)
    client_ip = models.GenericIPAddressField(null=True, blank=True)
    user_agent = models.TextField(blank=True)

    class Meta:
        ordering = ['-created_at']
        indexes = [
            models.Index(fields=['token_hash', 'is_active']),
            models.Index(fields=['user', 'is_active']),
        ]

    def __str__(self):
        return f"{self.user.username} - {self.application_name} ({self.target_app})"


class LoginSession(models.Model):
    """Track user login sessions for the UI client"""
    session_id = models.UUIDField(default=uuid.uuid4, unique=True)
    user = models.ForeignKey(User, on_delete=models.CASCADE)
    jwt_token = models.TextField()  # Store for session management
    created_at = models.DateTimeField(auto_now_add=True)
    last_activity = models.DateTimeField(auto_now=True)
    is_active = models.BooleanField(default=True)
    logged_out_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"{self.user.username} - {self.session_id}"

class PersistentToken(models.Model):
    # OneToOne ensures each user only ever has ONE row in this table
    user = models.OneToOneField(User, on_delete=models.CASCADE)
    access_token = models.TextField()
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"Token for {self.user.username}"

# auto revoke token
@receiver(post_save, sender=User)
def auto_revoke_on_password_change(sender, instance, **kwargs):
    """
    If the user's password is changed, automatically deactivate
    all of their tokens across the entire system.
    """
    if instance.pk: # Only run if the user already exists
        try:
            old_user = User.objects.get(pk=instance.pk)
            # Check if the hash has changed
            if old_user.password != instance.password:
                # This one line kills every token for this user instantly
                ServiceToken.objects.filter(user=instance, is_active=True).update(is_active=False)
                LoginSession.objects.filter(user=instance, is_active=True).update(is_active=False)
        except User.DoesNotExist:
            pass
